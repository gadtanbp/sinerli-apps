#!/bin/bash
# Sinai — Copyright © 2026 Gadtan x Gallen. All rights reserved.
# Builds Sinai.app (universal: Intel + Apple Silicon) and, with `dmg`, an installer DMG.
#
#   ./build.sh            release build  -> build/Sinai.app
#   ./build.sh dmg        release build  -> dist/macOS/Sinai-<version>.dmg (+ CARA-INSTAL.txt)
#   ./build.sh debug      debug build for this Mac only (enables SINAI_DEBUG_PORT automation)
#
# Versi diambil dari berkas VERSION. Naikkan sebelum merilis pembaruan:
#   scripts/bump-version.sh   (1.1.0 → 1.1.1 … 1.1.9 → 1.2.0)
#
# Requirements: Xcode or the Command Line Tools (`xcode-select --install`).
set -euo pipefail
cd "$(dirname "$0")"

# Satu sumber versi untuk semua platform (macOS, Windows, Linux, Android, iOS).
VERSION="$(tr -d '[:space:]' < VERSION)"
BUILD_NUMBER="$(date +%Y%m%d%H%M)"
MODE="${1:-release}"
APP="build/Sinai.app"
SDK="$(xcrun --sdk macosx --show-sdk-path)"
LOGO="Logo app/Logo Sinai.png"
SOURCES=(Sources/*.swift build/gen/BuildIntegrity.swift)
# ScreenCaptureKit (system-audio recording) is weak-linked: it only exists on
# macOS 12.3+, and Sinai still launches on older systems without it.
FRAMEWORKS=(-framework Cocoa -framework WebKit -framework PDFKit -framework Security -framework Vision -framework AVFoundation -framework Speech -Xlinker -weak_framework -Xlinker ScreenCaptureKit -framework SoundAnalysis -framework QuickLookThumbnailing -framework Contacts -framework EventKit -framework Photos -framework UserNotifications -framework Quartz)

rm -rf "$APP" build/obj
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" build/obj build/gen

# Integrity manifest of the web UI; the app refuses to start if bundled files change.
web_digest() {
  (cd "$1" && find . -type f ! -name .DS_Store | sed 's|^\./||' | LC_ALL=C sort | while IFS= read -r f; do
    printf '%s:%s\n' "$f" "$(shasum -a 256 "$f" | awk '{print $1}')"
  done) | shasum -a 256 | awk '{print $1}'
}
WEB_DIGEST="$(web_digest Resources/web)"
printf '// Generated by build.sh — do not edit.\nlet kWebIntegrity = "%s"\n' "$WEB_DIGEST" > build/gen/BuildIntegrity.swift

compile() { # arch target flags...
  local arch="$1" target="$2"; shift 2
  echo "› swiftc $arch ($target)"
  swiftc "$@" -target "$target" -sdk "$SDK" -module-name Sinai "${FRAMEWORKS[@]}" \
    -o "build/obj/Sinai-$arch" "${SOURCES[@]}"
}

if [ "$MODE" = "debug" ]; then
  HOST_ARCH="$(uname -m)"
  if [ "$HOST_ARCH" = "arm64" ]; then T="arm64-apple-macos11.0"; else T="x86_64-apple-macos10.15"; fi
  compile "$HOST_ARCH" "$T" -Onone -g -D DEBUG
  cp "build/obj/Sinai-$HOST_ARCH" "$APP/Contents/MacOS/Sinai"
else
  compile x86_64 x86_64-apple-macos10.15 -O -whole-module-optimization
  compile arm64 arm64-apple-macos11.0 -O -whole-module-optimization
  lipo -create build/obj/Sinai-x86_64 build/obj/Sinai-arm64 -output "$APP/Contents/MacOS/Sinai"
fi

sed -e "s/__VERSION__/$VERSION/" -e "s/__BUILD__/$BUILD_NUMBER/" Resources/Info.plist > "$APP/Contents/Info.plist"
printf 'APPL????' > "$APP/Contents/PkgInfo"
rsync -a --exclude .DS_Store Resources/web/ "$APP/Contents/Resources/web/"
if [ "$(web_digest "$APP/Contents/Resources/web")" != "$WEB_DIGEST" ]; then echo "integrity mismatch after copy" >&2; exit 1; fi

if [ ! -f build/AppIcon.icns ] || [ scripts/make-icon.swift -nt build/AppIcon.icns ] || [ "$LOGO" -nt build/AppIcon.icns ]; then
  echo "› rendering icon"
  rm -rf build/AppIcon.iconset
  swift scripts/make-icon.swift build/AppIcon.iconset "$LOGO" >/dev/null
  iconutil -c icns build/AppIcon.iconset -o build/AppIcon.icns
fi
cp build/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"

# Ad-hoc signature (required for Apple Silicon). For distribution without
# Gatekeeper warnings, re-sign with a Developer ID and notarize.
codesign --force --deep --sign - "$APP" >/dev/null 2>&1
echo "✓ $APP ($(du -sh "$APP" | cut -f1))"
lipo -info "$APP/Contents/MacOS/Sinai" | sed 's/^/  /'

if [ "$MODE" = "dmg" ]; then
  mkdir -p dist/macOS build/dmg
  rm -rf build/dmg/*
  cp -R "$APP" build/dmg/
  ln -s /Applications build/dmg/Applications
  sed "s/__VERSION__/$VERSION/g" scripts/panduan-instal/macOS.txt > build/dmg/CARA-INSTAL.txt
  cp build/dmg/CARA-INSTAL.txt dist/macOS/CARA-INSTAL.txt
  DMG="dist/macOS/Sinai-$VERSION.dmg"
  rm -f "$DMG"
  hdiutil create -volname "Sinai $VERSION" -srcfolder build/dmg -ov -format UDZO "$DMG" >/dev/null
  echo "✓ $DMG ($(du -sh "$DMG" | cut -f1))"
fi
